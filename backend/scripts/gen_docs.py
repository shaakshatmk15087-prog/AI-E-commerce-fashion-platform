"""Generate docs/API.md and docs/DATABASE.md from the code, so the docs cannot drift from reality.

    cd backend && python scripts/gen_docs.py

API auth classes: `public` = reachable without a token (verified by actually calling every route unauthenticated and
expecting 401 everywhere else); `token` = any signed-in user; `admin` / `stylist` = role-restricted (checked in the code and
by the authorization tests).
"""
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["TEST_DATABASE_URL"] = "sqlite:///:memory:"

from app import create_app  # noqa: E402
from app.config import TestConfig  # noqa: E402
from app.extensions import db  # noqa: E402


class DocConfig(TestConfig):
    TESTING = False  # use the real error handlers while probing


def role_of(rule):
    if rule.startswith("/api/v1/admin"):
        return "admin"
    if rule.startswith("/api/v1/stylist/") or re.match(r"/api/v1/consultations/<int:cid>/(accept|decline|complete)$", rule):
        return "stylist"
    return None


def describe(fn):
    doc = (fn.__doc__ or "").strip().splitlines()
    if doc:
        return doc[0].strip()
    return fn.__name__.replace("_", " ").capitalize()


def api_doc(app):
    client = app.test_client()
    groups = defaultdict(list)
    for rule in sorted(app.url_map.iter_rules(), key=lambda r: r.rule):
        if rule.endpoint == "static":
            continue
        url = re.sub(r"<[^>]+>", "1", rule.rule)
        for method in sorted(rule.methods - {"HEAD", "OPTIONS"}):
            status = client.open(url, method=method, json={}).status_code
            role = role_of(rule.rule)
            auth = role or ("token" if status == 401 else "public")
            groups[rule.rule.split("/")[3] if rule.rule.count("/") >= 3 else "root"].append(
                (method, rule.rule.replace("<int:", "{").replace(">", "}").replace("{pid", "{pid").replace("<", "{"),
                 auth, describe(app.view_functions[rule.endpoint])))
    out = ["# API reference", "",
           "Generated by `backend/scripts/gen_docs.py` from the running code. All paths are under the API host; JSON in, JSON out.",
           "Authentication is `Authorization: Bearer <token>` from `POST /api/v1/auth/login`. Errors look like "
           '`{"error": "...", "details": {...}, "request_id": "..."}`. Money is integer minor units (paise).', "",
           "| Auth | Meaning |", "|---|---|", "| public | no token needed |", "| token | any signed-in, active user |",
           "| stylist | stylist accounts only |", "| admin | administrators only |", ""]
    for g in sorted(groups):
        out += [f"## {g.replace('-', ' ').title()}", "", "| Method | Path | Auth | Purpose |", "|---|---|---|---|"]
        out += [f"| {m} | `{p}` | {a} | {d} |" for m, p, a, d in groups[g]]
        out.append("")
    total = sum(len(v) for v in groups.values())
    out.insert(3, f"{total} endpoints.")
    return "\n".join(out) + "\n"


def db_doc():
    out = ["# Database schema", "",
           "Generated by `backend/scripts/gen_docs.py` from the SQLAlchemy models (MySQL 8, InnoDB, utf8mb4). "
           "Migrations live in `backend/migrations`. Money is stored as integer minor units; all timestamps are UTC.", "",
           f"{len(db.metadata.sorted_tables)} tables.", ""]
    for t in db.metadata.sorted_tables:
        out += [f"## `{t.name}`", "", "| Column | Type | Null | Key / constraint |", "|---|---|---|---|"]
        fks = {c.name: fk for fk in t.foreign_keys for c in [fk.parent]}
        for c in t.columns:
            keys = []
            if c.primary_key:
                keys.append("PK")
            if c.name in fks:
                keys.append(f"FK -> {fks[c.name].target_fullname}")
            if c.unique:
                keys.append("unique")
            if c.index and not c.unique:
                keys.append("indexed")
            out.append(f"| {c.name} | {str(c.type)} | {'yes' if c.nullable else 'no'} | {', '.join(keys)} |")
        extra = [str(x) for x in t.constraints if x.__class__.__name__ in ("UniqueConstraint", "CheckConstraint") and getattr(x, "name", None)]
        for con in t.constraints:
            name = getattr(con, "name", None)
            if name and con.__class__.__name__ == "UniqueConstraint":
                out_cols = ", ".join(c.name for c in con.columns)
                extra.append(f"UNIQUE `{name}` ({out_cols})")
            elif name and con.__class__.__name__ == "CheckConstraint":
                extra.append(f"CHECK `{name}`: {con.sqltext}")
        extra = [e for e in extra if e.startswith(("UNIQUE", "CHECK"))]
        if extra:
            out += ["", "Constraints: " + "; ".join(extra)]
        out.append("")
    return "\n".join(out) + "\n"


def main():
    app = create_app(DocConfig)
    with app.app_context():
        db.create_all()
        docs = ROOT.parent / "docs"
        docs.mkdir(exist_ok=True)
        (docs / "API.md").write_text(api_doc(app), encoding="utf-8")
        (docs / "DATABASE.md").write_text(db_doc(), encoding="utf-8")
        print("wrote", docs / "API.md", "and", docs / "DATABASE.md")


if __name__ == "__main__":
    main()
